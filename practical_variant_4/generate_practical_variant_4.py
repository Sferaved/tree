def build_xlsx():
    wb = Workbook()
    ws = wb.active
    ws.title = "Практична варіант 4"
    bold = Font(name="Times New Roman", bold=True)
    normal = Font(name="Times New Roman")
    fill = PatternFill("solid", fgColor="D9EAF7")
    thin = Side(style="thin", color="000000")
    border = Border(left=thin, right=thin, top=thin, bottom=thin)

    ws["A1"] = "Практична робота, варіант 4"
    ws["A1"].font = Font(name="Times New Roman", bold=True, size=14)
    ws.merge_cells("A1:F1")
    ws["A1"].alignment = Alignment(horizontal="center")

    rows = [
        ["Показник", "Значення"],
        ["Загальний клас умов праці", overall_conditions_class],
        ["Кулачкова муфта: bracket", bracket],
        ["Кулачкова муфта: F, Н", F_preload],
        ["Кулачкова муфта: Fс, Н", F_trigger],
        ["Пружина: d розрах., мм", d_wire_calc],
        ["Пружина: τmax, МПа", tau_spring],
        ["Зрізний штифт: Tp, Н·м", Tp_pin],
        ["Зрізний штифт: dшт, мм", d_pin],
        ["Клапан котла: H", H_valve],
        ["Клапан котла: n розрах.", n_valves_calc],
        ["Клапан пневмопривода: p1, кгс/см²", p1],
        ["Клапан пневмопривода: F, мм²", F_needed],
        ["Обраний клапан: F, мм²", F_selected],
    ]
    for r, row in enumerate(rows, 3):
        for c, value in enumerate(row, 1):
            cell = ws.cell(r, c, value)
            cell.font = bold if r == 3 else normal
            cell.border = border
            cell.alignment = Alignment(vertical="center")
            if r == 3:
                cell.fill = fill
    ws.column_dimensions["A"].width = 42
    ws.column_dimensions["B"].width = 18

    start = 3
    col = 4
    ws.cell(start, col, "Фактор").font = bold
    ws.cell(start, col + 1, "Норматив").font = bold
    ws.cell(start, col + 2, "Факт").font = bold
    ws.cell(start, col + 3, "Клас").font = bold
    for c in range(col, col + 4):
        ws.cell(start, c).fill = fill
        ws.cell(start, c).border = border
        ws.cell(start, c).alignment = Alignment(horizontal="center")
    for i, (name, norm, fact, _, cls) in enumerate(work_conditions_rows, start + 1):
        for j, value in enumerate([name, norm, fact, cls], col):
            ws.cell(i, j, value).font = normal
            ws.cell(i, j).border = border
            ws.cell(i, j).alignment = Alignment(vertical="center")
    for c in range(4, 8):
        ws.column_dimensions[get_column_letter(c)].width = 24
    wb.save(XLSX)



ezp_sensitivity = [(x, UVP * ZS * (1 + x / 100)) for x in pss_values]
ess_iz_sensitivity = [(x, (VB / PB) * ((VRCB - VRCP) * x * K_BASE * CH)) for x in iz_values]
ess_k_sensitivity = [(x, (VB / PB) * ((VRCB - VRCP) * IZ_BASE * x * CH)) for x in k_values]


